# Arithmetic operators (+, -, *, /, //, %, **)

a = 10
b = 3

# 1. Floor Division (//)
# It divides two numbers and gives only the whole-number part of the result.
print(a // b)

# 2. Modulus (%)
# It gives the remainder after division.
print(a % b)

# 3. Exponentiation (**)
# It means power.
print( a ** b)      # 10^3 ---> 10 * 10 * 10 = 1000



