# DataType	    Meaning	                  Example

# int	        Whole numbers	          age = 21
# float	        Decimal numbers	          price = 99.50
# str	        Text	                  name = "Rajan"
# bool	        True or False	          is_student = True
# list	        Collection of values	  marks = [80, 90, 85]
# tuple	        Ordered collection	      numbers = (10, 20)
# set	        Unique values	          nums = {1, 2, 3}
# dict	        Key-value pairs	          student = {"name": "Rajan"}


# Example :
student_name = "Rajan"
age = 21
percentage = 85.5
is_student = True

print(student_name)
print(type(student_name))
print(age)
print(type(age))
print(percentage)
print(type(percentage))
print(is_student)
print(type(is_student))

# type() tells us which data type a variable contains.